// 1) 'number' + 3 + 3
// Початкові типи: 'number' (string), 3 (number), 3 (number).
// Правило: оператор + з рядком виконує конкатенацію (якщо хоча б один операнд - рядок), числа приводяться в рядки.
// Кроки:
//  - 'number' + 3 -> 'number3'  (3 приводиться в '3')
//  - 'number3' + 3 -> 'number33' (3 приводиться в '3')
// Результат: 'number33' (string)
console.log('1:', 'number' + 3 + 3); // 'number33'

// 2) null + 3
// Початкові типи: null, 3 (number).
// Правило: при арифметичних операціях null приводиться до числа -> 0.
// Кроки:
//  - +null => 0
//  - 0 + 3 => 3
// Результат: 3 (number)
console.log('2:', null + 3); // 3

// 3) 5 && "qwerty"
// Початкові типи: 5 (number, truthy), "qwerty" (string, truthy).
// Правило: && повертає перший falsy або останній операнд якщо всі truthy.
// Кроки:
//  - 5 -> truthy, тому перевіряється другий операнд
//  - другий операнд "qwerty" truthy -> повертається "qwerty"
// Результат: "qwerty" (string)
console.log('3:', 5 && "qwerty"); // 'qwerty'

// 4) +'40' + +'2' + "hillel"
// Початкові типи: '40' (string), '2' (string), "hillel" (string).
// Правило: унарний + приводить рядок до числа; потім + між number і number -> арифметика; number + string -> конкатенація.
// Кроки:
//  - +'40' -> 40 (number)
//  - +'2' -> 2 (number)
//  - 40 + 2 -> 42 (number)
//  - 42 + "hillel" -> "42hillel" (42 приводиться до рядка і відбувається конкатенація)
// Результат: "42hillel" (string)
console.log('4:', +'40' + +'2' + "hillel"); // '42hillel'

// 5) '10' - 5 === 6
// Початкові типи: '10' (string), 5 (number).
// Правило: оператор - приводить рядок до числа; === — строгий порівняльний оператор (без приведення типів).
// Кроки:
//  - '10' - 5 -> 10 - 5 = 5 (number)
//  - 5 === 6 -> порівнюємо числа без приведення -> false
// Результат: false (boolean)
console.log('5:', '10' - 5 === 6); // false

// 6) true + false
// Початкові типи: true, false.
// Правило: при числових операціях true -> 1, false -> 0.
// Кроки:
//  - true -> 1, false -> 0
//  - 1 + 0 = 1
// Результат: 1 (number)
console.log('6:', true + false); // 1

// 7) '4px' - 3
// Початкові типи: '4px' (string), 3 (number).
// Правило: при відніманні JS намагається привести рядок до числа; '4px' не є валідним числом -> результат NaN.
// Кроки:
//  - Number('4px') -> NaN
//  - NaN - 3 -> NaN
// Результат: NaN (тип number, але означає "не число")
console.log('7:', '4px' - 3); // NaN

// 8) '4' - 3
// Початкові типи: '4' (string), 3 (number).
// Правило: при арифметиці рядок приводиться до числа.
// Кроки:
//  - '4' -> 4
//  - 4 - 3 = 1
// Результат: 1 (number)
console.log('8:', '4' - 3); // 1

// 9) '6' + 3 ** 0
// Початкові типи: '6' (string), 3 (number), 0 (number).
// Пріоритет: оператор ** (степінь) виконується раніше ніж +.
// Правило: 3 ** 0 = 1; потім '6' + 1 -> рядкова конкатенація.
// Кроки:
//  - 3 ** 0 = 1
//  - '6' + 1 -> '61' (1 приводиться в '1')
// Результат: '61' (string)
console.log('9:', '6' + 3 ** 0); // '61'

// 10) 12 / '6'
// Початкові типи: 12 (number), '6' (string).
// Правило: при діленні рядок приводиться до числа.
// Кроки:
//  - '6' -> 6
//  - 12 / 6 = 2
// Результат: 2 (number)
console.log('10:', 12 / '6'); // 2

// 11) '10' + (5 === 6)
// Початкові типи: '10' (string); (5 === 6) дає false (boolean).
// Правило: + з рядком робить конкатенацію; boolean приводиться до рядка при конкатенації.
// Кроки:
//  - 5 === 6 -> false
//  - '10' + false -> '10false' (false приводиться в 'false')
// Результат: '10false' (string)
console.log('11:', '10' + (5 === 6)); // '10false'

// 12) null == ''
// Початкові типи: null і '' (порожній рядок).
// Правило: == робить нестроге порівняння з приведеннями, але спеціальне правило: null == undefined -> true, але null не рівне іншим примітивам (наприклад '', 0).
// Кроки:
//  - null == '' -> немає автоматичного приведення null до '' або навпаки; спеціальне правило повертає false
// Результат: false (boolean)
console.log('12:', null == ''); // false

// 13) 3 ** (9 / 3)
// Початкові типи: числа.
// Правило: дужки виконуються першими: 9 / 3 = 3; потім степінь.
// Кроки:
//  - 9 / 3 = 3
//  - 3 ** 3 = 27
// Результат: 27 (number)
console.log('13:', 3 ** (9 / 3)); // 27

// 14) !!'false' == !!'true'
// Початкові типи: обидва — непорожні рядки.
// Правило: будь-який непорожній рядок в логічному контексті -> truthy.
//  !! приводить value до boolean (двічі інвертує).
// Кроки:
//  - 'false' -> truthy -> !!'false' -> true
//  - 'true' -> truthy -> !!'true' -> true
//  - true == true -> true
// Результат: true (boolean)
console.log('14:', !!'false' == !!'true'); // true

// 15) 0 || '0' && 1
// Початкові типи: 0 (number, falsy), '0' (string, непорожній => truthy), 1 (number, truthy).
// Пріоритет: && виконується перед ||.
// Кроки:
//  - '0' && 1 -> повертає 1 (обидва truthy => повертається останній операнд)
//  - 0 || 1 -> повертає 1 (перший falsy -> повертається другий truthy)
// Результат: 1 (number)
console.log('15:', 0 || '0' && 1); // 1

// 16) (+null == false) < 1
// Початкові типи: null, false, числа.
// Правило і кроки:
//  - +null -> 0 (унарний плюс приводить null -> 0)
//  - 0 == false -> true (нестроге порівняння: false приводиться в 0)
//  - true при числовому порівнянні приводиться до 1
//  - 1 < 1 -> false
// Результат: false (boolean)
console.log('16:', (+null == false) < 1); // false

// 17) false && true || true
// Початкові типи: false (falsy), true (truthy).
// Пріоритет: && перед ||.
// Кроки:
//  - false && true -> false (перший falsy -> повертається він)
//  - false || true -> true (повертається перший truthy)
// Результат: true (boolean)
console.log('17:', false && true || true); // true

// 18) false && (false || true)
// Початкові типи: false, false, true.
// Кроки:
//  - (false || true) -> true (бо є true)
//  - false && true -> false (перший операнд falsy -> повертається він)
// Результат: false (boolean)
console.log('18:', false && (false || true)); // false

// 19) (+null == false) < 1 ** 5
// Початкові типи: null, false, числа.
// Пріоритет: ** виконується перед < ; дужки і порівняння як у прикладі 16.
// Кроки:
//  - +null -> 0
//  - 0 == false -> true
//  - 1 ** 5 -> 1
//  - true приводиться до 1 при числовому порівнянні
//  - 1 < 1 -> false
// Результат: false (boolean)
console.log('19:', (+null == false) < 1 ** 5); // false
